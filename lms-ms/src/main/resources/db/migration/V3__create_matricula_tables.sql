CREATE TABLE IF NOT EXISTS matriculas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_estudiante BIGINT,
    periodo_academico VARCHAR(20),
    fecha_creacion TIMESTAMP NOT NULL DEFAULT now(),
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE_VALIDACION',
    metodo_pago VARCHAR(20) NOT NULL,
    total NUMERIC(10,2),
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS matricula_detalles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_matricula BIGINT NOT NULL REFERENCES matriculas(id),
    id_contenido BIGINT NOT NULL,
    nombre_contenido VARCHAR(150),
    cantidad INTEGER NOT NULL,
    precio_unitario NUMERIC(10,2),
    PRIMARY KEY (id)
);
